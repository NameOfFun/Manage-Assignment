CREATE TABLE "Settings" (
  settingId   int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  name        varchar(50),
  type        varchar(50),
  value       varchar(50),
  description text,
  priority    int4,
  status      varchar(10),
  PRIMARY KEY (settingId)
);

CREATE TABLE "User" (
  user_id       int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  role_id       int4 NOT NULL,
  username      varchar(50) NOT NULL UNIQUE,
  password_hash text NOT NULL,
  email         varchar(50) NOT NULL UNIQUE,
  full_name     varchar(50) NOT NULL,
  status        varchar(10) NOT NULL,
  image_url     varchar(255) NULL,
  created_at    timestamp NOT NULL,
  PRIMARY KEY (user_id)
);

CREATE TABLE "Class" (
  class_id   int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  subject_id int4 NOT NULL,
  teacher_id int4 NOT NULL,
  class_code varchar(10) NOT NULL UNIQUE,
  semester   varchar(6) NOT NULL,
  year       int4 NOT NULL,
  PRIMARY KEY (class_id)
);

CREATE TABLE "AssignmentTemplate" (
  template_id int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  expert_id   int4 NOT NULL,
  subject_id  int4 NOT NULL,
  title       varchar(255) NOT NULL,
  instruction text,
  PRIMARY KEY (template_id)
);

CREATE TABLE "ClassAssignment" (
  assignment_id int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  class_id      int4 NOT NULL,
  template_id   int4,
  title         varchar(255) NOT NULL,
  instruction   text,
  start_date    timestamp NOT NULL,
  due_date      timestamp NOT NULL,
  status        varchar(10),
  PRIMARY KEY (assignment_id)
);

CREATE TABLE "Group" (
  group_id int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  class_id int4 NOT NULL,
  PRIMARY KEY (group_id)
);

CREATE TABLE "Scope" (
  scope_id      int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  assignment_id int4 NOT NULL,
  group_id      int4 NOT NULL,
  PRIMARY KEY (scope_id)
);

CREATE TABLE "AssignmentTask" (
  assignment_task_id int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  scope_id           int4 NOT NULL,
  task_name          varchar(255) NOT NULL,
  expected_hours     int4 NOT NULL,
  assigner           int4 NOT NULL,
  assignee           int4 NOT NULL,
  PRIMARY KEY (assignment_task_id)
);

CREATE TABLE "Submission" (
  submission_id int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  assignment_id int4 NOT NULL,
  student_id    int4 NOT NULL,
  group_id      int4 NOT NULL,
  submit_time   timestamp,
  status        varchar(10) NOT NULL,
  teacher_id    int4,
  score         float8,
  feedback      text,
  evaluated_at  timestamp,
  file_url      varchar(255) NOT NULL,
  PRIMARY KEY (submission_id)
);

CREATE TABLE "TimeLog" (
  log_id             int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
  student_id         int4 NOT NULL,
  assignment_task_id int4 NOT NULL,
  logged_date        timestamp NOT NULL,
  PRIMARY KEY (log_id)
);

-- Junction / Associate Tables (Composite Primary Keys)

CREATE TABLE "ClassStudent" (
  class_id   int4 NOT NULL,
  student_id int4 NOT NULL,
  enroll_date timestamp NOT NULL,
  PRIMARY KEY (class_id, student_id)
);

CREATE TABLE "GroupStudent" (
  user_id  int4 NOT NULL,
  group_id int4 NOT NULL,
  PRIMARY KEY (user_id, group_id)
);

CREATE TABLE "SubjectExpert" (
  subject_id int4 NOT NULL,
  user_id    int4 NOT NULL,
  PRIMARY KEY (subject_id, user_id)
);

